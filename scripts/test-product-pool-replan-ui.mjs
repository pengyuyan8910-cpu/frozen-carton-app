import assert from 'node:assert/strict';
import fs from 'node:fs';
const src=fs.readFileSync(new URL('./product-pool-replan-ui.mjs',import.meta.url),'utf8');
for(const label of ['导出当前产品池','全部门店重新排柜','重排指定门店','人工复核','导出最新版底表'])assert.ok(src.includes(label),`缺少按钮或文案：${label}`);
assert.ok(src.includes('productPoolReplanStoreSelect'),'指定门店重排必须提供门店选择框');
assert.ok(src.includes('buildFormalReuseResult(base,data,pool,[store])'),'指定门店必须先判断能否直接复用正式基准');
assert.match(src,/replanSelectedStores\(optimized\s*,\s*pool\s*,\s*\[store\]/,'发生产品池或门店变化时，指定门店只能把所选门店传给统一引擎包装层');
assert.ok(src.includes('产品池未变化，正式方案原样复用'),'UI必须明确提示无变化时不再重新优化');
assert.ok(src.includes('柜1-4第1-5层均参与冻品排柜'),'UI必须显示当前柜4规则');
assert.ok(src.includes('DRAFT_STORAGE_KEY'),'UI必须只写运营草稿');
assert.equal(src.includes('PUBLISHED_STORAGE_KEY'),false,'UI模块不得引用发布状态键');
assert.equal(src.includes('app-data.json'),false,'UI不得直接改正式app-data');
console.log('product pool replan ui contract tests passed');
